-- 00010: P1 课程问答区（先发后审：默认 visible，后台可隐藏；置顶沉淀 FAQ）

CREATE TABLE IF NOT EXISTS qa_question (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  owner_id BIGINT NOT NULL DEFAULT 1,
  package_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  content VARCHAR(500) NOT NULL DEFAULT '',
  anonymous TINYINT NOT NULL DEFAULT 0,
  status VARCHAR(16) NOT NULL DEFAULT 'visible',
  pinned TINYINT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_q_pkg (package_id, status),
  KEY idx_q_user (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS qa_answer (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  owner_id BIGINT NOT NULL DEFAULT 1,
  question_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  coach_id BIGINT NOT NULL DEFAULT 0,
  is_coach TINYINT NOT NULL DEFAULT 0,
  content VARCHAR(1000) NOT NULL DEFAULT '',
  status VARCHAR(16) NOT NULL DEFAULT 'visible',
  pinned TINYINT NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_a_q (question_id, status),
  KEY idx_a_user (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
